import type { AppContext } from '../../context.ts'
import { toTransactionDto, transactionSelect } from '../../db/selects.ts'
import type { Prisma } from '../../generated/prisma/client.ts'
import { badRequest } from '../../lib/errors.ts'
import { escapeLike, offsetFor } from '../../lib/pagination.ts'
import type { AuthUser } from '../../middleware/authenticate.ts'
import type { CreateTransactionInput, ExportTransactionsQuery, ListTransactionsQuery } from './transactions.schemas.ts'

// Safety cap so one report cannot load an unbounded number of rows.
export const EXPORT_ROW_LIMIT = 10_000

// Admins see every transaction; everyone else sees only their own.
function visibleWhere(actor: AuthUser, { q, status }: ExportTransactionsQuery): Prisma.TransactionWhereInput {
  return {
    ...(actor.role !== 'admin' && { userId: actor.id }),
    ...(status !== 'all' && { status }),
    ...(q && {
      OR: [
        { reference: { contains: escapeLike(q), mode: 'insensitive' } },
        { user: { name: { contains: escapeLike(q), mode: 'insensitive' } } },
      ],
    }),
  }
}

export function createTransactionsService({ db }: Pick<AppContext, 'db'>) {
  return {
    // Admins see every transaction; everyone else sees only their own.
    async list(actor: AuthUser, { q, status, page, pageSize }: ListTransactionsQuery) {
      const where = visibleWhere(actor, { q, status })

      // One database transaction, so the count and the page come from the same snapshot.
      const [total, rows] = await db.$transaction([
        db.transaction.count({ where }),
        db.transaction.findMany({
          where,
          orderBy: [{ createdAt: 'desc' }, { id: 'desc' }],
          skip: offsetFor(page, pageSize),
          take: pageSize,
          select: transactionSelect,
        }),
      ])

      return { items: rows.map(toTransactionDto), total, page, pageSize }
    },

    // Report: every matching transaction (up to EXPORT_ROW_LIMIT), newest first, with the same visibility rules as the list.
    async exportRows(actor: AuthUser, filters: ExportTransactionsQuery) {
      const rows = await db.transaction.findMany({
        where: visibleWhere(actor, filters),
        orderBy: [{ createdAt: 'desc' }, { id: 'desc' }],
        take: EXPORT_ROW_LIMIT,
        select: transactionSelect,
      })
      return rows.map(toTransactionDto)
    },

    async create(actor: AuthUser, input: CreateTransactionInput) {
      let customerId = actor.id

      if (actor.role === 'admin' && input.customerId !== undefined) {
        const customer = await db.user.findUnique({
          where: { id: input.customerId },
          select: { id: true, isActive: true },
        })
        if (!customer?.isActive) {
          throw badRequest('Choose an active customer.', {
            fieldErrors: { customerId: ['Choose an active customer.'] },
          })
        }
        customerId = customer.id
      }

      const row = await db.transaction.create({
        // The reference is generated by the database from the id.
        data: { userId: customerId, amount: input.amount.toFixed(2), note: input.note },
        select: transactionSelect,
      })
      return toTransactionDto(row)
    },
  }
}

export type TransactionsService = ReturnType<typeof createTransactionsService>
